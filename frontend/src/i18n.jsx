const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => {
    const savedLanguage = window.localStorage.getItem('agri-language');
    return savedLanguage === 'ta' ? 'ta' : 'en';
  });

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const setLanguage = (nextLanguage) => {
    const validLanguage = nextLanguage === 'ta' ? 'ta' : 'en';
    window.localStorage.setItem('agri-language', validLanguage);
    document.documentElement.lang = validLanguage;
    setLanguageState(validLanguage);
  };

  const value = useMemo(() => ({
    language,
    setLanguage,
    t: (text) => translateText(text, language),
    cropLabel: (crop) => typeof crop === 'string' ? translations[language][crop] || crop : crop
  }), [language]);

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
}

function translateText(text, language) {
  if (typeof text !== 'string') {
    return text;
  }

  const translation = translations[language][text];
  if (translation) {
    return translation;
  }
  if (language !== 'ta') {
    return text;
  }
  if (text.includes(', ')) {
    return text.split(', ').map((part) => translateText(part, language)).join(', ');
  }

  const patterns = [
    [/^High nitrogen requirement identified for (.+) in (.+) with current N level \((.+) mg\/kg\)\.$/, (crop, soil, amount) => `${translateText(crop, language)} பயிருக்கு ${translateText(soil, language)} மண்ணில் நைட்ரஜன் தேவை அதிகம்; தற்போதைய அளவு ${amount} mg/kg.`],
    [/^Phosphorus deficiency correction required for root development in (.+)\.$/, (soil) => `${translateText(soil, language)} மண்ணில் வேர் வளர்ச்சிக்காக பாஸ்பரஸ் குறைபாட்டைச் சரிசெய்ய வேண்டும்.`],
    [/^Balanced primary nutrient boost \(N-P-K\) optimal for (.+) grown in (.+)\.$/, (crop, soil) => `${translateText(soil, language)} மண்ணில் வளரும் ${translateText(crop, language)} பயிருக்கு சமச்சீர் N-P-K ஊட்டம் ஏற்றது.`],
    [/^Potassium reinforcement needed to enhance stress tolerance and yield quality in (.+)\.$/, (soil) => `${translateText(soil, language)} மண்ணில் அழுத்தத் தாங்குதிறன் மற்றும் மகசூல் தரத்தை மேம்படுத்த பொட்டாசியம் தேவை.`],
    [/^Low organic carbon level \((.+)%\) detected in (.+)\. Vermicompost rebuilds soil microbiome\.$/, (amount, soil) => `${translateText(soil, language)} மண்ணில் கரிம கார்பன் அளவு குறைவாக உள்ளது (${amount}%). மண்புழு உரம் மண் நுண்ணுயிர் சூழலை மேம்படுத்தும்.`],
    [/^Acidic\/alkaline pH balance \((.+)\) and soil pest suppression required in (.+)\.$/, (ph, soil) => `${translateText(soil, language)} மண்ணில் pH சமநிலை (${ph}) மற்றும் மண் பூச்சிக் கட்டுப்பாடு தேவை.`],
    [/^Micronutrient supplementation required for heavy feeding crop \((.+)\) in (.+)\.$/, (crop, soil) => `${translateText(soil, language)} மண்ணில் அதிக ஊட்டம் தேவைப்படும் ${translateText(crop, language)} பயிருக்கு நுண்ணூட்டம் வழங்க வேண்டும்.`],
    [/^Dataset ML model recommended (.+) based on learned multi-feature agricultural patterns\.$/, (fertilizer) => `வேளாண் தரவுகளில் கற்ற பல அம்சங்களின் அடிப்படையில் ${translateText(fertilizer, language)} உரத்தை மாதிரி பரிந்துரைக்கிறது.`]
  ];

  for (const [pattern, format] of patterns) {
    const match = text.match(pattern);
    if (match) {
      return format(...match.slice(1));
    }
  }
  return text;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within LanguageProvider.');
  }
  return context;
}
